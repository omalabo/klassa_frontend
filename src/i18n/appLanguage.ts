// ─── Langues supportées ─────────────────────────────────────
export type AppLang = 'en' | 'fr' | 'es' | 'ar' | 'zh'

export const SUPPORTED_APP_LANGS: AppLang[] = [
  'en',
  'fr',
  'es',
  'ar',
  'zh'
]

// ─── Détection automatique ─────────────────────────────────
export function detectAppLanguage(): AppLang {
  try {
    // Optionnel : si plus tard tu veux forcer une langue manuellement
    const stored = localStorage.getItem('app_lang') as AppLang | null

    if (stored && SUPPORTED_APP_LANGS.includes(stored)) {
      return stored
    }
  } catch {
    // localStorage indisponible
  }

  const languages = (navigator as any).languages

  const raw =
    (Array.isArray(languages) && languages[0]) ||
    navigator.language ||
    'en'

  // Exemple : fr-FR -> fr, es-MX -> es, zh-CN -> zh
  const base = raw.toLowerCase().split('-')[0] as AppLang

  if (SUPPORTED_APP_LANGS.includes(base)) {
    return base
  }

  return 'en'
}

