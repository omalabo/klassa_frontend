// ─── Hook React ─────────────────────────────────────────────
export function useAppLanguage() {
  const [lang] = useState<AppLang>(detectAppLanguage)

  useEffect(() => {
    document.documentElement.lang = lang

    // ⚠️ Active ceci seulement si ton interface est prête pour RTL
    // document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])

  const t = useCallback(
    (key: string) => {
      return translations[lang]?.[key] || translations.en[key] || key
    },
    [lang]
  )

  return {
    lang,
    t
  }
}